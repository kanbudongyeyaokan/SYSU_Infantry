/**
 * @file    Referee_task.c
 * @brief   裁判系统处理任务 (验收专用版)
 * @note    包含 User口接收检查 和 图传UI发送测试
 */

#include "Referee_task.h"
#include "referee.h"
#include "cmsis_os.h"  // 包含 osDelay
#include "robot_task.h"


// ---------------------------------------------------------
// 外部引用
// ---------------------------------------------------------
// 假设裁判系统连接的是 UART6，且在 main.c 中已生成 huart6

static Referee_Data_t* referee_data;


// ---------------------------------------------------------
// 任务主体
// ---------------------------------------------------------
void Referee_task(void const * argument)
{
    // =====================================================
    // 1. 硬件初始化
    // =====================================================
    // 启动裁判系统串口接收 (DMA模式)
    referee_data = Referee_Get_Data(&huart6);

    // 延时等待系统稳定，防止上电瞬间数据不稳定
    osDelay(500);

    // =====================================================
    // 2. 任务主循环
    // =====================================================
    for(;;)
    {

        // [验收提示 - 接收]
        // 在 Debug 模式下将 ref 添加到 Live Watch：
        // 1. 观察 ref->is_online 是否为 1 (代表收到过机器人状态包)
        // 2. 观察 ref->robot_status.robot_id 是否正确 (如 1 或 101)
        // 3. 敲击装甲板，观察 ref->robot_hurt 数据变化

        // 1. is_online: %d (整数)
        // 2. current_hp: %d (uint16_t 也是整数)
        Uart_printf(test_uart, "Online:%d, HP:%d\r\n",
                    referee_data->is_online,
                    referee_data->robot_status.current_hp);

        // -------------------------------------------------
        // B. 发送 UI 测试包 (验证发送链路 / 图传数据)
        // -------------------------------------------------
        // [验收提示 - 发送]
        // 调用此函数后，观察电源管理模块(PM02)上的 User 指示灯
        // 或者 Tx 指示灯是否快速闪烁。
        // 如果闪烁，说明 C板 -> PM02 的发送链路正常。
        // Referee_Send_UI_Test();

        // -------------------------------------------------
        // C. 频率控制
        // -------------------------------------------------
        // 官方建议 UI 包频率不要超过 10Hz
        // 这里设置为 200ms (5Hz)，足够验收且安全，不会堵塞串口
        osDelay(200);
    }
}